# 实验 4-2 阶梯电价计算
# 电价为教学用的简化数值，实际电价以当地供电部门公布的为准
# 第一档：200 度及以内，每度 0.59 元
# 第二档：201～400 度的部分，每度 0.64 元
# 第三档：超过 400 度的部分，每度 0.89 元

kwh = float(input("本月用电量（度）："))

if kwh < 0:
    print("用电量不能是负数，请检查输入")
elif kwh <= 200:
    fee = kwh * 0.59
    print(f"第一档，电费 {fee:.2f} 元")
elif kwh <= 400:
    fee = 200 * 0.59 + (kwh - 200) * 0.64
    print(f"第二档，电费 {fee:.2f} 元")
else:
    fee = 200 * 0.59 + 200 * 0.64 + (kwh - 400) * 0.89
    print(f"第三档，电费 {fee:.2f} 元")
