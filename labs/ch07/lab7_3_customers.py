# 实验 7-3 两天顾客名单对比
# 周六、周日来店消费的会员编号（虚构，同一个人一天可能来几次）
sat = ["M003", "M015", "M027", "M003", "M041", "M052", "M015", "M008"]
sun = ["M015", "M033", "M041", "M008", "M060", "M033", "M019"]

a = set(sat)            # 转成集合，自动去掉重复
b = set(sun)
print("周六来了", len(sat), "人次，", len(a), "位会员")
print("周日来了", len(sun), "人次，", len(b), "位会员")

print("两天都来的：", sorted(a & b))       # 交集
print("周末来过的一共：", len(a | b), "位")  # 并集
print("只有周六来的：", sorted(a - b))     # 差集
print("只来了一天的：", sorted(a ^ b))     # 对称差集
print("M060 周六来过吗？", "M060" in a)
