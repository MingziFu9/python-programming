def main():
    G = g.parse()
    terms = {}
    for ch, lst in sorted(G.items()):
        for t, a, d in lst:
            terms.setdefault(t, (ch, a, d))
    E, bad = [], []
    for b, pres in PRE.items():
        for a in pres:
            if a not in terms or b not in terms:
                bad.append(f"{a} → {b}（不在术语表中）")
            elif terms[a][0] > terms[b][0]:
                bad.append(f"{a}（第 {terms[a][0]} 章）→ {b}（第 {terms[b][0]} 章）：先修概念在后面的章")
            else:
                E.append([a, b])
    nodes = [{"id": t, "ch": ch, "cat": CAT_OF_CH[ch], "a": a, "d": d} for t, (ch, a, d) in terms.items()]
    old = (LG / "data.js").read_text(encoding="utf-8")
    head = old[:old.index("var NODES")]
    head = head.replace(head[head.index("var CATS"):head.index(";", head.index("var CATS")) + 1],
                        "var CATS = " + json.dumps(CATS, ensure_ascii=False) + ";")
    body = "var NODES = [\n" + ",\n".join("  " + json.dumps(n, ensure_ascii=False) for n in nodes) + "\n];\n"
    body += "var EDGES = " + json.dumps(E, ensure_ascii=False) + ";\n"
    (LG / "data.js").write_text(head + body, encoding="utf-8")
    print(f"节点 {len(nodes)}，先修关系 {len(E)}")
    if bad:
        print("有问题的先修关系：", *bad, sep="\n  ")
    nopre = [t for t in terms if t not in PRE]
    print("没有写先修的概念（作为起点）：", nopre)


main()
